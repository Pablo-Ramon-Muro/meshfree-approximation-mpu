function DM = DistanceMatrixCSRBF(dsites, ctrs, ep)
% =========================================================================
% DistanceMatrixCSRBF
% -------------------------------------------------------------------------
% Builds the distance matrix between a set of data points and
% a set of centres, meant for radial basis functions with COMPACT
% SUPPORT (CSRBF). Unlike a normal distance matrix, this one
% is returned as a sparse matrix: only the
% distances falling INSIDE the support of the RBF are stored (the rest are discarded,
% because the RBF is zero there). This is what makes the method
% scalable in memory and cost for large sets of points.
%
% IMPORTANT, about the format of the distance:
%   The ij-th entry of the matrix is 1-ep*r, where
% r=||data_i-centre_j||_2 if point i is inside the patch generated by
% centre j (r < 1/ep) and 0 if it is outside, so if it is 0, being sparse
% it is not stored. The 1-ep*r form is used to rescale: at most it is almost 1, or
% else less.
%
% INPUTS:
%   dsites : N x s matrix. Each row is a data point in R^s
%            (N points, s = dimension of the space).
%   ctrs   : M x s matrix. Each row is the centre of an RBF
%            (M centres).
%   ep     : scalar > 0. Shape parameter. The support radius of the
%            RBF is 1/ep: a small ep gives a large support (wide function),
%            a large ep gives a small support (narrow function).
%
% OUTPUT:
%   DM     : SPARSE N x M matrix. Entry (i,j) is 1 - ep*r_ij, with
%            r_ij = distance between data point i and centre j, ONLY
%            if r_ij < 1/ep (inside the support); otherwise the
%            entry is 0 (not stored, since it is sparse). We take 1-ep*r
%            to give a larger value to the points that are closer
%            to the centre.
% =========================================================================

    % Number of data points (N) and of centres (M).
    N = size(dsites,1);
    M = size(ctrs,1);

    % --- Support radius of the RBF ---
    % The support of the CSRBF is 1/ep: beyond that distance the function
    % is zero. We will use it as the search radius to discard distant
    % pairs.
    support = 1/ep;

    % --- Memory reservation for the lists of the sparse matrix ---
    % Instead of filling the matrix directly, we accumulate, for
    % each non-zero entry, its row (rowidx), its column (colidx) and its
    % value (validx); at the end we assemble the sparse matrix in one go with
    % sparse(). We estimate how many non-zero entries there will be in order to reserve
    % the memory just once (avoiding reallocating memory inside the loop,
    % which is slow). The 25*N bound is an estimate of the number of neighbours
    % inside the support; if it falls short MATLAB would grow it by itself, but
    % it is better to get it right.
    nzmax = 25*N;
rowidx = zeros(1,nzmax);    % row indices of each non-zero entry
colidx = zeros(1,nzmax);    % column indices of each non-zero entry
validx = zeros(1,nzmax);    % value (1-ep*r) of each non-zero entry
%these will then be the first three inputs of sparse, to build the
%sparse matrix by giving it the non-zero values and their positions

% Pointers to write into the previous lists in blocks:
% istart = first free position, iend = last position written.
istart = 1;
iend   = 0;

% --- Choice of strategy depending on whether there are more centres or more data ---
% The k-D tree (a fast spatial search structure) is built
% on one of the two sets and queried with the other. It is better to
% build the tree on the larger set and to loop over
% the smaller one, because that way fewer queries are made
% (each query to the tree is cheap, and fewer loop iterations is
% better). We check this with an if
if M > N
    % --- Case: more centres than data ---
    % We build the tree on the CENTRES and loop over the DATA.
    Tree = createns(ctrs, 'NSMethod', 'kdtree');

    % We go through each data point i.
    for i = 1:N
        % Range query: we ask the tree for all the CENTRES that
        % are at a distance smaller than 'support' from data point i,
        % that is, the centres whose support covers this data point.
        [idx_cell, dist_cell] = rangesearch(Tree, dsites(i,:), support);
        idx = idx_cell{1}'; % Transposed to a column
        dist = dist_cell{1}'; % Transposed to a column

        % How many centres fell inside the support of this data point.
        newentries = length(idx);

        % We advance the end pointer: we are going to add 'newentries'
        % new entries to the lists.
        iend = iend + newentries;

        % We fill the block [istart:iend] of the three lists:
        % - row: for a fixed i (fixed data point), all these entries
        % are in the same row (row i) (this data point), which is why
        % repmat(i,...) repeats the index i as many times as
        %    centres were found (newentries)
        rowidx(istart:iend) = repmat(i,1,newentries);%it collects
        % all the row indices of the non-zero data; when you move on to the
        % next i, istart and iend are increased by the newentries of
        % data point i (not of i+1), so that every
        % index is stored.

            % - column: the indices of the centres found (idx). For
            % a given data point, as the centre varies, the column varies.
            colidx(istart:iend) = idx';
            % - value: the distance in shifted form, 1 - ep*dist. This
            %   is the value u = 1 - ep*r that we will put at the position of
            % row and column given by rowidx and colidx, which CSRBF expects
            % to receive.
            validx(istart:iend) = 1 - ep*dist';

            %we initialise for the next data point.
            istart = istart + newentries;
    end
else
    % --- Case: more data than centres (or equal) ---
    % Symmetric to the previous one: we build the tree on the data and
    % loop over the centres. It is the usual case in interpolation
    % (there are as many centres as data, or looping over centres is
    % convenient).
    Tree = createns(dsites, 'NSMethod', 'kdtree');

      % We go through each centre j.
      for j = 1:M
          % We ask the tree for all the DATA inside the support of
          % centre j (the data that the RBF centred at j reaches).
          [idx_cell, dist_cell] = rangesearch(Tree, ctrs(j,:), support);
          idx = idx_cell{1}'; % Transposed to a column
          dist = dist_cell{1}'; % Transposed to a column

            % Number of data points found for this centre.
            newentries = length(idx);
            iend = iend + newentries;

            % We fill the corresponding block:
            % - row: the indices of the data points found (idx). Here
            %   the row is the data point and the column is centre j (the matrix DM
            % is N x M = data x centres), which is why the roles are swapped
            %   with respect to the previous case.
            rowidx(istart:iend) = idx';
            % - column: all of them in column j (this centre).
            colidx(istart:iend) = repmat(j,1,newentries);
            % - value: as before, shifted distance 1 - ep*dist.
            validx(istart:iend) = 1 - ep*dist';

            istart = istart + newentries;
      end
end

% --- Assembly of the sparse matrix ---
% find(rowidx) locates the positions of the lists that were actually used
% (it discards the extra space reserved in nzmax that stayed at zero). Without
      % this, the leftover entries (with row 0) would spoil the assembly.
      idx = find(rowidx);%it looks at which elements are not 0, because when initialising
      % at the beginning we set a vector of 25*N zeros. There is no need to do it
      % for the columns and the values too, because the zeros will be in the same
      % places. So we do rowidex(idex), colidex(idex), validex(idex).

      % sparse(rows, columns, values, N, M) builds the sparse matrix
      % N x M placing 'values' at the positions (rows, columns)
      % given. We take only the valid positions (idx).
      DM = sparse(rowidx(idx), colidx(idx), validx(idx), N, M);

end
